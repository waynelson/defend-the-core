def client(name, mob):
    ident = f"dm:{name}"
    if mob.get("template"):
        # A Mojang client entity in the 1.8/1.10 format, renamed (tools/templates).
        data = json.loads((ROOT / f"tools/templates/{mob['template']}.entity.json").read_text(encoding="utf-8"))
        data["minecraft:client_entity"]["description"]["identifier"] = ident
        return data

    animations = dict(HUMANOID_ANIMATIONS)
    controllers = list(HUMANOID_CONTROLLERS)
    if mob["base"] == "zombie":
        geometry, material = "geometry.zombie.v1.8", "zombie"
        animations["zombie_attack_bare_hand"] = "animation.zombie.attack_bare_hand"
        controllers.append({"zombie_attack_bare_hand": "controller.animation.zombie.attack_bare_hand"})
        egg = "spawn_egg_zombie"
    else:
        geometry, material = "geometry.skeleton.v1.8", "skeleton"
        animations["bow_and_arrow"] = "animation.humanoid.bow_and_arrow"
        animations["skeleton_attack"] = "animation.skeleton.attack"
        controllers.append({"bow_and_arrow": "controller.animation.humanoid.bow_and_arrow"})
        controllers.append({"skeleton_attack": "controller.animation.skeleton.attack"})
        egg = "spawn_egg_skeleton"
    return {
        "format_version": "1.8.0",
        "minecraft:client_entity": {"description": {
            "identifier": ident,
            "min_engine_version": "1.8.0",
            "materials": {"default": material},
            "textures": {"default": mob["texture"]},
            "geometry": {"default": geometry},
            "scripts": HUMANOID_SCRIPTS,
            "animations": animations,
            "animation_controllers": controllers,
            "render_controllers": ["controller.render.default"],
            "enable_attachables": True,
            "spawn_egg": {"texture": egg},
        }},
    }


# ---------------------------------------------------------------- write


def write(path, data):
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def main():
    for name, mob in ROSTER.items():
        write(BP / f"{name}.json", behavior(name, mob))
        write(RP / f"{name}.entity.json", client(name, mob))
    write_defenses()
    lang = ROOT / "packs/RP/texts/en_US.lang"
    lines = [
        "pack.name=Defend the Core Resources",
        "pack.description=Client entities for Defend the Core",
        "entity.dm:core.name=Core",
    ]
    for name, mob in ROSTER.items():
        lines.append(f"entity.dm:{name}.name={mob['name']}")
        lines.append(f"item.spawn_egg.entity.dm:{name}.name=Spawn {mob['name']}")
    for name, turret in TURRETS.items():
        lines.append(f"entity.dm:{name}.name={turret['name']}")
    lines.append("entity.dm:vendor.name=Vendor")
    lines.append("action.interact.dtc_turret=Repair / Upgrade")
    lines.append("entity.dm:label.name=Label")
    for item_id, item in ITEMS.items():
        lines.append(f"item.dm:{item_id}={item['name']}")
    lang.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(ROSTER)} mobs; {GEN_NOTE}")


