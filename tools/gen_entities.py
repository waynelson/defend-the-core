def target_entry(family, max_dist, must_see, priority=None):
    entry = {
        "filters": {"test": "is_family", "subject": "other", "value": family},
        "max_dist": max_dist,
        "must_see": must_see,
    }
    if priority is not None:
        entry["priority"] = priority
    return entry


def targeting_groups(flyer=False):
    common = {"priority": 2, "must_see": False, "reselect_targets": True, "within_radius": 64}
    if flyer:
        # Flyers sit well above the core; without this they never pick it up.
        common["target_search_height"] = 80
    return {
        # Core only; ignores players unless hurt by one.
        "dm:tgt_core_only": {
            "minecraft:behavior.nearest_attackable_target": {
                **common, "entity_types": [target_entry("dm_core", 64, False)],
            }
        },
        # Core first, players inside the aggro radius second.
        "dm:tgt_prioritized": {
            "minecraft:behavior.nearest_prioritized_attackable_target": {
                **common,
                "entity_types": [
                    target_entry("dm_core", 64, False, 0),
                    # Turrets close by are fair game (players can lose them).
                    target_entry("dm_turret", 8, True, 1),
                    target_entry("player", 6, True, 2),
                ],
            }
        },
        # Whichever valid target is nearest.
        "dm:tgt_nearest": {
            "minecraft:behavior.nearest_attackable_target": {
                **common,
                "entity_types": [
                    target_entry("dm_core", 64, False),
                    target_entry("dm_turret", 8, True),
                    target_entry("player", 6, True),
                ],
            }
        },
    }


def targeting_events():
    names = ["dm:tgt_core_only", "dm:tgt_prioritized", "dm:tgt_nearest"]
    return {
        name: {
            "remove": {"component_groups": [n for n in names if n != name]},
            "add": {"component_groups": [name]},
        }
        for name in names
    }


